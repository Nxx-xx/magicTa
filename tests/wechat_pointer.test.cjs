const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(process.argv[2] || 'build/wechat/adapter.js', 'utf8');
assert.match(source, /ontouchstart:\s*null/);
const start = source.indexOf('let _towerLastPointer');
const end = source.indexOf('let _touchDebugCount', start);
assert.ok(start >= 0 && end > start);
const sandbox = {Date, _evtCanvas: {}};
vm.createContext(sandbox);
vm.runInContext(source.slice(start, end), sandbox);
const make = sandbox._toPointerEvt;
make('pointerdown', {clientX: 100, clientY: 200});
let event = make('pointermove', {clientX: 110, clientY: 160});
assert.equal(event.movementX, 10);
assert.equal(event.movementY, -40);
event = make('pointermove', {clientX: 107, clientY: 155});
assert.equal(event.movementX, -3);
assert.equal(event.movementY, -5);
make('pointerup', {clientX: 107, clientY: 155});
event = make('pointerdown', {clientX: 220, clientY: 300});
assert.equal(event.movementY, 0);
assert.equal(event.buttons, 1);
const cancel = source.slice(source.indexOf('if (typeof _api.onTouchCancel'));
assert.ok(cancel.indexOf('_dispatchEvent("touchcancel"') < cancel.indexOf('_dispatchEvent("pointercancel"'), 'native cancellation precedes mouse release');
console.log('PASS: touchscreen discovery and incremental pointer movement for drag scrolling');
